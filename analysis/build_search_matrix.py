"""Build an exploratory search matrix from independently recomputed September metrics."""
from pathlib import Path
import pandas as pd
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'analysis'
q=pd.read_csv(OUT/'SQP_搜索词诊断.csv')
q['样本曝光份额']=q['样本曝光']/q['市场曝光'].replace(0,np.nan)
q['点击吸引力指数']=q['样本点击率']/q['市场点击每曝光比'].replace(0,np.nan)
q['购买承接指数']=q['相对市场购买指数']
q['样本条件']=np.where(q['样本点击']>=100,'≥100点击；仍需核查稳定性','<100点击；仅观察')
q['机会象限']=np.select([
    q['样本点击'].lt(100)|q['点击吸引力指数'].isna()|q['购买承接指数'].isna(),
    q['点击吸引力指数'].ge(1)&q['购买承接指数'].ge(1),
    q['点击吸引力指数'].ge(1)&q['购买承接指数'].lt(1),
    q['点击吸引力指数'].lt(1)&q['购买承接指数'].ge(1)],
    ['样本不足，先观察','吸引与承接均达基准','能吸引点击，购买承接偏低','购买承接达基准，点击吸引偏低'],
    default='点击与购买均偏低')
q['建议关注']=q['机会象限'].map({
    '样本不足，先观察':'先积累同词同ASIN数据，不据此直接调广告。',
    '吸引与承接均达基准':'结合绝对购买率、相关性、广告成本、库存和份额，再决定维护或增长测试。',
    '能吸引点击，购买承接偏低':'查规格与词意图、价格、页面、库存、评价和广告位置；不直接断言页面问题。',
    '购买承接达基准，点击吸引偏低':'查展示位置、主图、标题、价格与竞品构成；符合利润要求后小额测试。',
    '点击与购买均偏低':'先查商品与词意图是否匹配，避免仅因市场搜索大就加预算。'})
q['判断边界']='1倍仅为描述性分界；非统计显著性。样本结构和位置可影响差异；不是自然流量指标。'
cols=['搜索词','市场搜索量','样本曝光','样本点击','样本购买','样本点击率','市场点击每曝光比',
      '样本点击后购买率','市场点击后购买率','样本曝光份额','点击份额','购买份额',
      '点击吸引力指数','购买承接指数','样本条件','机会象限','建议关注','判断边界']
q=q[cols].sort_values('样本点击',ascending=False)
q.to_csv(OUT/'9月_搜索机会矩阵.csv',index=False,encoding='utf-8-sig')


print('September search matrix:',len(q),'terms')
